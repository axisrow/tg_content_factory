CYRILLIC_RE = re.compile(r"[а-яА-ЯёЁ]")

# Случайно сгенерированные username. Три формы спам-генератора:
#  - сплошной КАПС+цифры, длина ≥10: "S0IMD1EDUAW", "EXF74CHE3RZ1";
#  - CamelCase-слова + хвост ≥3 цифр, ≥2 заглавных и ≥2 строчных
#    ("WordWord123456"): ферма 02.10.26 — 18/18 поймано, 0/1429 ложных
#    на живой БД;
#  - короткая ферма (#1510, 09.10.26): 8-9 символов КАПС+цифры с цифрой
#    ВНУТРИ имени (первые 6 позиций) — "UB1JH44UM", "K66CING9V". Калибровка
#    на живой БД: 1558 username, 0 ложных (контрольные "BITCOIN24"/
#    "NASDAQNEWS" чисты — их цифры в хвосте/отсутствуют), +48 новых истинных
#    поймано сверх известных 9 (китайская спам-карусель, 111-144 подписчика).
#    Остаток: 12-буквенные без цифр ("XUBIIGFIDALF") сознательно НЕ ловим —
#    форма "^[A-Z]{12,}$" даёт ложняк на реальных именах ("SHAMSINURIJODI").
# Безопасные случаи остаются за бортом: "BITCOIN24" (9 символов, цифры
# только в хвосте), "NASDAQNEWS" (нет цифр), "PublicChannel42" (1 заглавная,
# 2 цифры), "JohnDoe1990" (7 букв, годовой хвост). Lowercase-only фермы
# ("haberkanal724"-стиль) сознательно не ловим — слишком много легитимных.
SUSPICIOUS_USERNAME_RE = re.compile(
    r"^(?=.*\d)[A-Z0-9]{10,}$"  # сплошной КАПС + цифры
    r"|^(?=.*[A-Z].*[A-Z])(?=.*[a-z].*[a-z])[A-Za-z]{8,}\d{3,}$"  # CamelCase+хвост
    r"|^(?=[A-Z0-9]{8,9}$)[A-Z0-9]{0,5}\d[A-Z0-9]{2,}$"  # короткая ферма: внутренняя цифра
)

